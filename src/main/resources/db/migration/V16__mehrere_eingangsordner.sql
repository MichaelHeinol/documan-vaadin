-- Mehrere überwachte Eingangsordner. Der bisher eingestellte wird der erste in der Liste.
CREATE TABLE consume_folder (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder varchar(500) NOT NULL UNIQUE
);

INSERT INTO consume_folder (folder)
SELECT coalesce((SELECT folder FROM consume_settings WHERE id = 1), 'eingang');

DROP TABLE consume_settings;
