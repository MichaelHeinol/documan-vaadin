-- Was der Mailanbieter als Spam kennzeichnet, bleibt liegen. Auch in bestehenden Postfächern.
ALTER TABLE mail_account ADD COLUMN skip_spam boolean NOT NULL DEFAULT true;

-- Trifft eine Regel zu, bleibt die Nachricht unverändert im Postfach.
CREATE TABLE mail_exclusion_rule (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint       NOT NULL REFERENCES mail_account ON DELETE CASCADE,
    field      varchar(10)  NOT NULL,
    value      varchar(255) NOT NULL
);

CREATE INDEX mail_exclusion_rule_account_idx ON mail_exclusion_rule (account_id);
