-- Kategorien ordnen Dokumente oberhalb der Dokumenttypen, etwa Finanzen / Bank / Girokonto. Sie lassen
-- sich bis zu fünf Stufen tief schachteln, die Tiefe prüft das Programm. Auf derselben Stufe ist jeder
-- Name nur einmal vergeben, unter verschiedenen Kategorien darf er sich wiederholen.
-- Die Spalten der automatischen Zuordnung teilt die Tabelle mit den anderen Stammdaten. Kategorien kommen
-- aber über den Dokumenttyp oder den Unterordner im Eingangsordner, die Regeln bleiben deshalb leer.
CREATE TABLE category (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL,
    algorithm   varchar(10)  NOT NULL DEFAULT 'none',
    match_text  varchar(500) NOT NULL DEFAULT '',
    ignore_case boolean      NOT NULL DEFAULT true,
    parent_id   bigint       REFERENCES category ON DELETE SET NULL,
    UNIQUE NULLS NOT DISTINCT (parent_id, name)
);
CREATE INDEX category_parent_idx ON category (parent_id);

-- Die Kategorie eines Dokumenttyps gilt für seine Dokumente ohne eigene Kategorie.
ALTER TABLE document_type ADD COLUMN category_id bigint REFERENCES category ON DELETE SET NULL;
CREATE INDEX document_type_category_idx ON document_type (category_id);

-- Eine eigene Kategorie des Dokuments, etwa aus dem Unterordner im Eingangsordner, geht der des Typs vor.
ALTER TABLE document ADD COLUMN category_id bigint REFERENCES category ON DELETE SET NULL;
CREATE INDEX document_category_idx ON document (category_id);

-- Die Kategorien bilden die obersten Ordnerebenen der Ablage. Alle Dateien ziehen beim nächsten Lauf
-- des Workers um, zunächst nach „Ohne Kategorie“.
UPDATE document SET file_sync_pending = true WHERE status IN ('done', 'failed');

-- Die tägliche Übersicht kann die Kategorien zeigen, vorhandene Einstellungen bekommen den Abschnitt dazu.
ALTER TABLE daily_report
    ADD COLUMN categories_chart varchar(4) NOT NULL DEFAULT 'bars',
    ALTER COLUMN sections SET DEFAULT 'documents,per_day,sources,types,categories,activities,mailboxes,folders,backup,storage';
-- Die Reihenfolge der Mail folgt dem Programm, nicht dieser Liste.
UPDATE daily_report SET sections = sections || ',categories'
WHERE sections NOT LIKE '%categories%' AND sections <> '';
