CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(150) NOT NULL UNIQUE,
    password_hash varchar(200) NOT NULL,
    superuser     boolean      NOT NULL DEFAULT false,
    active        boolean      NOT NULL DEFAULT true,
    created       timestamptz  NOT NULL DEFAULT now(),
    last_login    timestamptz
);

CREATE TABLE correspondent (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL UNIQUE,
    algorithm   varchar(10)  NOT NULL DEFAULT 'none',
    match_text  varchar(500) NOT NULL DEFAULT '',
    ignore_case boolean      NOT NULL DEFAULT true
);

CREATE TABLE document_type (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL UNIQUE,
    algorithm   varchar(10)  NOT NULL DEFAULT 'none',
    match_text  varchar(500) NOT NULL DEFAULT '',
    ignore_case boolean      NOT NULL DEFAULT true
);

CREATE TABLE tag (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL UNIQUE,
    algorithm   varchar(10)  NOT NULL DEFAULT 'none',
    match_text  varchar(500) NOT NULL DEFAULT '',
    ignore_case boolean      NOT NULL DEFAULT true,
    color       varchar(7)   NOT NULL DEFAULT '#3f7d6e'
);

CREATE TABLE document (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             varchar(300) NOT NULL,
    correspondent_id  bigint       REFERENCES correspondent ON DELETE SET NULL,
    document_type_id  bigint       REFERENCES document_type ON DELETE SET NULL,
    document_date     date,
    notes             text         NOT NULL DEFAULT '',
    inbox             boolean      NOT NULL DEFAULT true,
    content           text         NOT NULL DEFAULT '',
    page_count        integer,
    original          varchar(500) NOT NULL,
    archive           varchar(500) NOT NULL DEFAULT '',
    thumbnail         varchar(500) NOT NULL DEFAULT '',
    original_filename varchar(500) NOT NULL,
    mime_type         varchar(100) NOT NULL,
    size              bigint       NOT NULL DEFAULT 0,
    checksum          varchar(64)  NOT NULL UNIQUE,
    source            varchar(10)  NOT NULL DEFAULT 'upload',
    source_detail     varchar(500) NOT NULL DEFAULT '',
    status            varchar(10)  NOT NULL DEFAULT 'pending',
    error             text         NOT NULL DEFAULT '',
    attempts          smallint     NOT NULL DEFAULT 0,
    file_sync_pending boolean      NOT NULL DEFAULT false,
    added             timestamptz  NOT NULL DEFAULT now(),
    modified          timestamptz  NOT NULL DEFAULT now(),
    search_vector     tsvector
);

CREATE INDEX document_search_vector_idx ON document USING gin (search_vector);
CREATE INDEX document_title_trgm_idx ON document USING gin (title gin_trgm_ops);
CREATE INDEX document_content_trgm_idx ON document USING gin (content gin_trgm_ops);
CREATE INDEX document_date_idx ON document (document_date);
CREATE INDEX document_added_idx ON document (added);
CREATE INDEX document_status_idx ON document (status);
CREATE INDEX document_file_sync_idx ON document (file_sync_pending) WHERE file_sync_pending;
CREATE INDEX document_correspondent_idx ON document (correspondent_id);
CREATE INDEX document_type_idx ON document (document_type_id);

CREATE TABLE document_tag (
    document_id bigint NOT NULL REFERENCES document ON DELETE CASCADE,
    tag_id      bigint NOT NULL REFERENCES tag ON DELETE CASCADE,
    PRIMARY KEY (document_id, tag_id)
);

CREATE INDEX document_tag_tag_idx ON document_tag (tag_id);

CREATE TABLE mail_account (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    varchar(100) NOT NULL UNIQUE,
    enabled                 boolean      NOT NULL DEFAULT true,
    host                    varchar(255) NOT NULL,
    port                    integer      NOT NULL DEFAULT 993,
    security                varchar(10)  NOT NULL DEFAULT 'ssl',
    username                varchar(255) NOT NULL,
    password_encrypted      text         NOT NULL DEFAULT '',
    folder                  varchar(255) NOT NULL DEFAULT 'INBOX',
    only_unseen             boolean      NOT NULL DEFAULT true,
    maximum_age_days        integer      NOT NULL DEFAULT 30,
    filter_from             varchar(255) NOT NULL DEFAULT '',
    filter_subject          varchar(255) NOT NULL DEFAULT '',
    attachments             varchar(5)   NOT NULL DEFAULT 'pdf',
    after_import            varchar(10)  NOT NULL DEFAULT 'seen',
    target_folder           varchar(255) NOT NULL DEFAULT '',
    assign_correspondent_id bigint       REFERENCES correspondent ON DELETE SET NULL,
    assign_document_type_id bigint       REFERENCES document_type ON DELETE SET NULL,
    last_check_at           timestamptz,
    last_error              text         NOT NULL DEFAULT '',
    imported_count          integer      NOT NULL DEFAULT 0
);

CREATE TABLE mail_account_tag (
    mail_account_id bigint NOT NULL REFERENCES mail_account ON DELETE CASCADE,
    tag_id          bigint NOT NULL REFERENCES tag ON DELETE CASCADE,
    PRIMARY KEY (mail_account_id, tag_id)
);

-- Merkt sich importierte Nachrichten, auch wenn sie im Postfach unverändert bleiben.
CREATE TABLE processed_mail (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   bigint       NOT NULL REFERENCES mail_account ON DELETE CASCADE,
    message_id   varchar(500) NOT NULL,
    subject      varchar(500) NOT NULL DEFAULT '',
    processed_at timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (account_id, message_id)
);

-- Zeitplan der Datensicherung. Es gibt genau einen Datensatz.
CREATE TABLE backup_settings (
    id             integer      PRIMARY KEY,
    enabled        boolean      NOT NULL DEFAULT false,
    frequency      varchar(10)  NOT NULL DEFAULT 'daily',
    weekday        smallint     NOT NULL DEFAULT 6,
    time           time         NOT NULL DEFAULT '02:00',
    folder         varchar(255) NOT NULL DEFAULT '',
    keep           smallint     NOT NULL DEFAULT 7,
    last_scheduled timestamptz
);

-- Auftrag an den Worker und zugleich Verlauf.
CREATE TABLE backup_run (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          varchar(10)  NOT NULL,
    origin        varchar(30)  NOT NULL DEFAULT '',
    status        varchar(10)  NOT NULL DEFAULT 'queued',
    archive       varchar(500) NOT NULL DEFAULT '',
    safety_backup boolean      NOT NULL DEFAULT false,
    size          bigint,
    documents     integer,
    files         integer,
    message       text         NOT NULL DEFAULT '',
    error         text         NOT NULL DEFAULT '',
    queued_at     timestamptz  NOT NULL DEFAULT now(),
    started_at    timestamptz,
    finished_at   timestamptz
);

CREATE INDEX backup_run_status_idx ON backup_run (status);
