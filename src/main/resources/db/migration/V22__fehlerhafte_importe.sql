-- Dateien, die nicht als Dokument angenommen wurden, etwa Duplikate, leere oder zu große Dateien. Sie bleiben
-- mit Grund und Herkunft sichtbar, bis jemand sie entfernt. Die ältesten Einträge fallen nach 500 weg.
CREATE TABLE import_rejection (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created              timestamptz   NOT NULL DEFAULT now(),
    source               varchar(20)   NOT NULL,
    filename             varchar(500)  NOT NULL,
    reason               varchar(1000) NOT NULL,
    added_by             varchar(150)  NOT NULL DEFAULT '',
    source_detail        varchar(500)  NOT NULL DEFAULT '',
    existing_document_id bigint REFERENCES document (id) ON DELETE SET NULL
);

CREATE INDEX import_rejection_created_idx ON import_rejection (created DESC);
